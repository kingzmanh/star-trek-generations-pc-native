"""Collect the runtime's exported natives (non-static `void api_<Name>(void)` in
src/rt/*.c) into src/rt/apitab.c: the table api_lookup searches after the
static tables of win32.c / threads.c.  Run by the Makefile before building."""
import os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'rt')
names = []
for fn in sorted(os.listdir(root)):
    if not fn.endswith('.c') or fn == 'apitab.c':
        continue
    for m in re.finditer(r'^void api_(\w+)\(void\)\s*\{', open(os.path.join(root, fn), encoding='latin1').read(), re.M):
        names.append(m.group(1))
names = sorted(set(names))
out = ['/* generated by tools/gen_apitab.py - do not edit */', '#include "rt.h"', '']
out += ['void api_%s(void);' % n for n in names]
out += ['', 'typedef struct { const char *name; NativeFn fn; } ApiEnt;', 'const ApiEnt api_tab_rt[] = {']
out += ['    {"%s", api_%s},' % (n, n) for n in names]
out += ['    {0, 0}', '};', '']
text = '\n'.join(out)
p = os.path.join(root, 'apitab.c')
if not os.path.exists(p) or open(p).read() != text:
    open(p, 'w').write(text)
print('%d natives' % len(names))
